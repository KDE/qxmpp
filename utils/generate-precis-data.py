"""
Generates src/base/QXmppPrecisData_p.h from the Unicode Character Database.

The PRECIS derived property (RFC 8264, section 8) needs two code point
properties that Qt does not expose: Default_Ignorable_Code_Point and
Hangul_Syllable_Type. Everything else is taken from QChar at runtime.

Usage: generate-precis-data.py <UCD directory> > src/base/QXmppPrecisData_p.h

The UCD directory needs DerivedCoreProperties.txt and HangulSyllableType.txt
(e.g. /usr/share/unicode from Debian's unicode-data package, or
https://www.unicode.org/Public/<version>/ucd/).
"""

import re
import sys
from pathlib import Path


def parse(path: Path, wanted: set[str]) -> tuple[str, list[tuple[int, int]]]:
    version = ""
    ranges = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not version:
            m = re.match(r"#\s*\S+-(\d+\.\d+\.\d+)\.txt", line)
            if m:
                version = m.group(1)
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cps, prop = (field.strip() for field in line.split(";")[:2])
        if prop not in wanted:
            continue
        first, _, last = cps.partition("..")
        ranges.append((int(first, 16), int(last or first, 16)))
    return version, merge(ranges)


def merge(ranges: list[tuple[int, int]]) -> list[tuple[int, int]]:
    merged: list[tuple[int, int]] = []
    for first, last in sorted(ranges):
        if merged and first <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], last))
        else:
            merged.append((first, last))
    return merged


def emit(name: str, ranges: list[tuple[int, int]]) -> str:
    lines = [f"inline constexpr CodePointRange {name}[] = {{"]
    lines += [f"    {{ 0x{first:04X}, 0x{last:04X} }}," for first, last in ranges]
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    ucd = Path(sys.argv[1])
    version, ignorable = parse(ucd / "DerivedCoreProperties.txt", {"Default_Ignorable_Code_Point"})
    _, jamo = parse(ucd / "HangulSyllableType.txt", {"L", "V", "T"})

    print(f"""\
// SPDX-FileCopyrightText: 2026 Linus Jahn <lnj@kaidan.im>
//
// SPDX-License-Identifier: LGPL-2.1-or-later

// Generated by utils/generate-precis-data.py from Unicode {version}. Do not edit.

#ifndef QXMPPPRECISDATA_P_H
#define QXMPPPRECISDATA_P_H

namespace QXmpp::Private::Precis {{

struct CodePointRange {{
    char32_t first;
    char32_t last;
}};

// Default_Ignorable_Code_Point (DerivedCoreProperties.txt)
{emit("defaultIgnorable", ignorable)}

// Hangul_Syllable_Type is L, V or T (HangulSyllableType.txt)
{emit("oldHangulJamo", jamo)}

}}  // namespace QXmpp::Private::Precis

#endif  // QXMPPPRECISDATA_P_H""")


if __name__ == "__main__":
    main()
